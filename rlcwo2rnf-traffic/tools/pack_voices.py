#!/usr/bin/env python3
"""The recorded voices (VOICE_PROMPTS.md), packed into the game.

Reads every .mp3 in rlcwo2rnf-traffic/voices/ and writes src/49_voices.js: VOICES, each file's name (without .mp3)
to its bytes as a data: URI, for 60_police.js to decode the first time it plays one. A line with no file is simply
not heard, so the voices can arrive a few at a time: put them in voices/, run this, run build.sh. No code changes.

usage: python3 tools/pack_voices.py
"""
import os, base64, json, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
VD = os.path.join(ROOT, 'voices'); OUT = os.path.join(ROOT, 'src', '49_voices.js')
names = sorted(f for f in os.listdir(VD) if f.lower().endswith('.mp3')) if os.path.isdir(VD) else []
out = {}; total = 0
for f in names:
    b = open(os.path.join(VD, f), 'rb').read(); total += len(b)
    if b[:3] != b'ID3' and not (b[0] == 0xFF and (b[1] & 0xE0) == 0xE0):
        sys.exit(f'{f}: not an MP3')
    out[os.path.splitext(f)[0]] = 'data:audio/mpeg;base64,' + base64.b64encode(b).decode('ascii')
with open(OUT, 'w', encoding='utf-8') as o:
    o.write('/* GENERATED by tools/pack_voices.py: do not edit by hand. The recorded voices (VOICE_PROMPTS.md), from\n'
            '   rlcwo2rnf-traffic/voices/: each name to its MP3. Empty until they arrive; a line with no file is not heard. */\n')
    o.write('const VOICES=' + json.dumps(out, separators=(',', ':')) + ';\n')
print(f'{len(out)} voices, {total/1024:.0f} KB of MP3 -> {os.path.relpath(OUT, ROOT)}')
