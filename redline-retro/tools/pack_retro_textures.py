"""Redline Retro's ground pictures: the owner's texture pack (the full game's 49_textures.js, 1024 px webp each)
drawn down to SIZE x SIZE and cut to COLORS colours (a palette, as a PlayStation's 4- and 8-bit textures had), laid
twice as large on the ground (SCALE_K) so each texel reads as a chunky square. Writes src/49_textures.js.
usage: python3 tools/pack_retro_textures.py path/to/full/49_textures.js [SIZE] [COLORS]"""
import sys, re, io, base64
from PIL import Image
src = open(sys.argv[1], encoding='utf8').read()
SIZE = int(sys.argv[2]) if len(sys.argv) > 2 else 64
COLORS = int(sys.argv[3]) if len(sys.argv) > 3 else 32
SCALE_K = 2.0
rows = []
for m in re.finditer(r'\{id:"([^"]+)",t:"([A-Z0-9]+)",m:\[([^\]]+)\],scale:([\d.]+),has:(true|false),src:"([^"]*)"\}', src):
    id_, t, mean, scale, has, data = m.groups()
    out = ''
    if has == 'true':
        raw = base64.b64decode(data.split(',', 1)[1])
        im = Image.open(io.BytesIO(raw)).convert('RGB')
        # (down in two steps: a box filter to 4x, then Lanczos, so the grain survives as texels, not as mush)
        im = im.resize((SIZE * 4, SIZE * 4), Image.BOX).resize((SIZE, SIZE), Image.LANCZOS)
        q = im.quantize(colors=COLORS, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        b = io.BytesIO(); q.save(b, format='PNG', optimize=True)
        out = 'data:image/png;base64,' + base64.b64encode(b.getvalue()).decode()
    rows.append(f'{{id:"{id_}",t:"{t}",m:[{mean}],scale:{float(scale) * SCALE_K:g},has:{has},src:"{out}"}}')
js = ('/* GENERATED by tools/pack_retro_textures.py: do not edit by hand. The owner\'s ground pictures as a late-90s console\n'
      f'   would have held them: {SIZE} x {SIZE}, {COLORS} colours each, laid twice as large. */\n'
      f'const TEXPACK={{size:{SIZE},layers:[\n' + ',\n'.join(rows) + '\n]};\n')
open('src/49_textures.js', 'w', encoding='utf8').write(js)
print(len(js), 'bytes,', len(rows), 'layers')
