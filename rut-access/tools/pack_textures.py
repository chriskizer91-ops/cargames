#!/usr/bin/env python3
"""The ground's photographs, packed into the game.

Reads textures/<name>.png (the owner's texture packs, see TEXTURES.md), makes each one tile (the half-offset
blend: the edges of the tile are taken from its own middle, which is continuous across the wrap, faded in over a
band), flattens any baked-in shading (the slow part of the brightness is evened out so the renderer's light is
the only light), resizes to SIZE, encodes WebP and writes src/49_textures.js: TEXPACK, one layer a surface, in
the order the shader's T_ defines expect (13_lit.js), with each picture's mean colour in linear light (what the
shader divides by to lay the picture's grain over the procedural colour) and its scale in metres a tile.
A surface with no picture gets an empty layer; the shader leaves that surface as it was.

usage: python3 tools/pack_textures.py [--size 1024] [--quality 78] [--preview out.png]
"""
import sys, os, io, json, base64, argparse
import numpy as np
from PIL import Image, ImageFilter

HERE=os.path.dirname(os.path.abspath(__file__)); ROOT=os.path.dirname(HERE)
# name, metres a tile, how hard to flatten baked shading (0..1), whether the picture has a direction (ribs, planks, ruts: a narrower blend across them)
LAYERS=[('dirt_red',2,.45,0),('dirt_red_2',2,.45,0),('grass_dry',2,.4,0),('grass_dry_2',2,.4,0),('trail',2,.45,1),('gravel',1.5,.5,0),
  ('asphalt',2,.4,0),('strip_rubber',2,.45,1),('rock',1.5,.8,0),('ruts_dry',3.1,.7,1),('mud_wet',2,.7,0),('playa',3,.5,0),('clay_red',2,.5,0),
  ('concrete',2,.45,0),('wood_planks',1,.5,1),('sheet_metal',1,.6,1),('hay',1,.5,1)]

def smooth(t):
    t=np.clip(t,0,1);return t*t*(3-2*t)

def flatten(a,strength):
    """even out the slow brightness: a big blur of the luminance, divided out (partly), the mean kept"""
    if strength<=0:return a
    L=a@np.array([.299,.587,.114],dtype=np.float32)
    small=Image.fromarray((np.clip(L,0,1)*255).astype(np.uint8)).resize((256,256),Image.BOX)
    blur=np.asarray(small.filter(ImageFilter.GaussianBlur(14)).resize(a.shape[1::-1],Image.BILINEAR)).astype(np.float32)/255
    mean=L.mean();f=(mean/np.maximum(blur,.04))**strength
    f=np.clip(f,.55,1.8)
    out=a*f[...,None];out*=mean/max(1e-4,(out@np.array([.299,.587,.114],dtype=np.float32)).mean())
    return np.clip(out,0,1)

def seamless(a,directional):
    """the half-offset blend, over a band at each edge: wide where the picture has no direction, narrow across a direction"""
    h,w,_=a.shape;sh=np.roll(np.roll(a,h//2,0),w//2,1)
    bx=(.06 if directional else .15)*w;by=.15*h
    x=np.arange(w);dx=np.minimum(x,w-1-x);rx=smooth(1-dx/bx)
    y=np.arange(h);dy=np.minimum(y,h-1-y);ry=smooth(1-dy/by)
    m=np.maximum(rx[None,:],ry[:,None])[...,None]
    return a*(1-m)+sh*m

def linear_mean(a):
    c=np.where(a<=.04045,a/12.92,((a+.055)/1.055)**2.4);return [round(float(v),4) for v in c.reshape(-1,3).mean(0)]

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--size',type=int,default=1024);ap.add_argument('--quality',type=int,default=78);ap.add_argument('--preview',default='')
    o=ap.parse_args();tdir=os.path.join(ROOT,'textures');out=[];previews=[];total=0
    for name,scale,flat,direc in LAYERS:
        f=os.path.join(tdir,name+'.png')
        if not os.path.exists(f):
            f2=os.path.join(tdir,name+'.jpg');f=f2 if os.path.exists(f2) else None
        if not f:
            out.append({'id':name,'m':[.5,.5,.5],'scale':scale,'has':False,'src':''});print(f'{name:14} (no picture)');continue
        im=Image.open(f).convert('RGB');a=np.asarray(im).astype(np.float32)/255
        a=flatten(a,flat);a=seamless(a,bool(direc))
        im=Image.fromarray((np.clip(a,0,1)*255+.5).astype(np.uint8)).resize((o.size,o.size),Image.LANCZOS)
        buf=io.BytesIO();im.save(buf,'WEBP',quality=o.quality,method=6);b=buf.getvalue();total+=len(b)
        m=linear_mean(np.asarray(im).astype(np.float32)/255)
        out.append({'id':name,'m':m,'scale':scale,'has':True,'src':'data:image/webp;base64,'+base64.b64encode(b).decode('ascii')})
        print(f'{name:14} {im.size[0]}px  {len(b)/1024:6.0f} KB  mean {m}')
        if o.preview:
            t=im.resize((160,160),Image.LANCZOS);tile=Image.new('RGB',(320,320));[tile.paste(t,(x,y)) for x in (0,160) for y in (0,160)];previews.append((name,tile))
    js='/* GENERATED by tools/pack_textures.py from textures/*.png: do not edit by hand. The ground\'s photographs (the\n   owner\'s texture packs), made seamless, flattened and packed; a layer a surface, in the order 13_lit.js\'s T_ defines\n   name them. m: the mean colour in linear light. scale: metres a tile. */\n'
    js+='const TEXPACK={size:%d,layers:[\n'%o.size
    js+=',\n'.join('{id:%s,m:%s,scale:%s,has:%s,src:%s}'%(json.dumps(l['id']),json.dumps(l['m']),json.dumps(l['scale']),'true' if l['has'] else 'false',json.dumps(l['src'])) for l in out)
    js+='\n]};\n'
    with open(os.path.join(ROOT,'src','49_textures.js'),'w') as fh:fh.write(js)
    print(f'src/49_textures.js: {len(js)/1048576:.2f} MB ({total/1048576:.2f} MB of WebP)')
    if o.preview and previews:
        from PIL import ImageDraw
        cols=6;rows=(len(previews)+cols-1)//cols;sheet=Image.new('RGB',(cols*328+8,rows*346+8),(20,20,28));d=ImageDraw.Draw(sheet)
        for i,(n,t) in enumerate(previews):
            x=8+(i%cols)*328;y=8+(i//cols)*346;sheet.paste(t,(x,y+18));d.text((x,y+2),n,fill=(230,230,240))
        sheet.save(o.preview);print('preview',o.preview)
if __name__=='__main__':main()
