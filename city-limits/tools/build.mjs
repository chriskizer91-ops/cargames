/* City Limits: build the one-file game.
   1. The car modules (hd/, Dirt Sleeper HD's cars, physics, Sim level and Digital Engine, plus City Limits'
      new cars) are global-scope scripts. They are joined into one ES module (build/hd.gen.js) with the
      names the game needs exported, so nothing in them can clash with Shiftlight 3's modules.
   2. esbuild bundles src/game/main.js (Shiftlight 3's renderer and world code, and City Limits' own)
      into one script, dropped into game/index.html.
   node tools/build.mjs            -> dist/city-limits.html
   node tools/build.mjs --fragment -> also dist/city-limits.artifact.html (no doctype/html/head/body tags) */
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {dirname,join} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';

const root=join(dirname(fileURLToPath(import.meta.url)),'..');
let esbuild;
try{esbuild=await import('esbuild');}
catch(e){esbuild=await import(pathToFileURL('/opt/npm-tools/node_modules/esbuild/lib/main.js').href);}

/* ---------- 1. the car modules as one ES module ---------- */
export const HD_MODS=['10_core','12_gl_mesh','13_lit','14_loft','15_digital_engine','16_engines','17_audio','21_suv','22_faces','23_parts',
  '25_coupe','29_hatch','34_ev','35_wedge','36_hyper','30_wheels','31_engine_bay','32_builds','33_car_mesh',
  '40_physics','41_ground','42_chassis','43_sim','37_newbuilds','45_ev','56_parts','57_ratings','58_clparts'];
const EXPORTS=['BUILDS','CARS','BODIES','MAT','MM','truck','truckFar','buildWheel','specOf','engineSpec','ENGINE_OF','buildChassis','makeCar','cgOf',
  'setLow','setLockers','GroundWorld','Vehicle','ASSISTS','SIM','makeDSP','initAudio','voiceNode','ENG','setRoom','setVolume','lin',
  'SIMSET','SIMDEV','SIM_AIR','SIM_WX','HCG','RUNNING','TREAD_MU','SURF_RR','evSound','EV',
  'SLOTS','SLOT_GROUPS','slotName','slotOptions','slotLabel','fits','fixRig','rigBuild','rigKey','presetRig','presetsOf','PRESET_PARTS','CAR_PARTS','ENGINES','PAINTS','WHEELS','GLOWS',
  'rateBuild','rateRig','TERRAINS','TERRAIN_SHORT','measure60','rigCost'];
export function hdModule(){
  let src='/* generated by tools/build.mjs from hd/*.js: do not edit */\n';
  for(const m of HD_MODS){let s;try{s=readFileSync(join(root,'hd',m+'.js'),'utf8');}catch(e){continue;}src+=`\n/* ===== hd/${m}.js ===== */\n`+s+'\n';}
  /* meshes stay on the CPU: the game's renderer uploads them in its own layout */
  src=src.replace('function makeMesh(d){','function makeMesh(d){return {cpu:true,pos:d.pos,nrm:d.nrm,col:d.col,mat:d.mat,n:d.pos.length/3};');
  /* City Limits keeps its own settings */
  src=src.replace(/'dsmini-engine'/g,"'cl-engine'");
  const have=EXPORTS.filter(n=>new RegExp(`(^|\\n)\\s*(const|let|var|function|class|async function)\\s+${n}\\b`).test(src));
  src+=`\nexport {${have.join(',')}};\n`;
  return src;
}

if(import.meta.url===pathToFileURL(process.argv[1]).href){
  mkdirSync(join(root,'build'),{recursive:true});mkdirSync(join(root,'dist'),{recursive:true});
  writeFileSync(join(root,'build','hd.gen.js'),hdModule());
  const frag=process.argv.includes('--fragment'),minify=process.argv.includes('--minify');
  const res=await esbuild.build({entryPoints:[join(root,'src/game/main.js')],bundle:true,format:'iife',target:'es2022',write:false,
    minifySyntax:true,minifyWhitespace:minify,minifyIdentifiers:minify,legalComments:'none',logLevel:'warning',charset:'utf8'});
  let js=res.outputFiles[0].text;
  if(/<\/script/i.test(js))js=js.replace(/<\/script/gi,'<\\/script');
  const tpl=readFileSync(join(root,'game/index.html'),'utf8');
  const page=tpl.replace('/*@BUNDLE@*/',()=>js);
  const split=page.indexOf('<!--@BODY@-->');
  const head=page.slice(0,split).trim(),body=page.slice(split).replace('<!--@BODY@-->','').trim();
  const full=`<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">\n<meta name="mobile-web-app-capable" content="yes">\n<meta name="apple-mobile-web-app-capable" content="yes">\n<meta name="theme-color" content="#05040a">\n${head}\n</head>\n<body>\n${body}\n</body>\n</html>\n`;
  writeFileSync(join(root,'dist','city-limits.html'),full);
  if(frag)writeFileSync(join(root,'dist','city-limits.artifact.html'),`${head}\n${body}\n`);
  console.log(`dist/city-limits.html  ${(full.length/1024).toFixed(1)} KB`);
}
